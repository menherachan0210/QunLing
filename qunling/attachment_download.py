"""Bounded disk-backed attachment transfer with validated HTTP range recovery."""
from __future__ import annotations

import asyncio
import hashlib
import json
import math
import os
from pathlib import Path
import re
import time
from urllib.parse import urljoin, urlsplit

import aiohttp

from qunling.network import PublicResolver, validate_public_url, WebError

MAX_BYTES = 40 * 1024 * 1024
MAX_SECONDS = 720
IDLE_SECONDS = 30
MAX_ATTEMPTS = 4


class DownloadError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def budget(size):
    return min(MAX_SECONDS, max(180, 60 + math.ceil(size / 65536))) if size else MAX_SECONDS


def _save(path, state):
    temporary = path.with_suffix('.tmp')
    with temporary.open('w', encoding='utf-8') as stream:
        os.chmod(temporary, 0o600)
        json.dump(state, stream)
    temporary.replace(path)


def _validator(headers):
    etag = headers.get('ETag', '')
    if etag and not etag.startswith('W/'):
        return 'ETag', etag
    return 'Last-Modified', headers.get('Last-Modified', '')


async def download_file(url, path, *, expected_size=0, progress=None, timeout=None, immutable_id=''):
    """Keep a partial file for explicit resume; never concatenate changed objects.

    Paths are generated by the trusted job owner, never taken from a model or
    HTTP filename. The sidecar contains no URL, password or other credential.
    """
    if type(expected_size) is not int or not 0 <= expected_size <= MAX_BYTES:
        raise DownloadError('size_limit', '附件超过 40 MiB 处理上限。')
    timeout = budget(expected_size) if timeout is None else timeout
    if type(timeout) not in (int, float) or not math.isfinite(timeout) or not 0 < timeout <= MAX_SECONDS:
        raise ValueError('Invalid download deadline')
    validate_public_url(url)
    # QQ upload IDs identify immutable objects, but its FTN CDN omits HTTP
    # validators. In that case verify a 64 KiB overlap before appending ranges.
    host = urlsplit(url).hostname or ''
    source_key = hashlib.sha256(immutable_id.encode()).hexdigest() if (
        isinstance(immutable_id, str) and 0 < len(immutable_id) <= 4096
        and host.endswith('.ftn.qq.com')) else ''
    path = Path(path)
    meta = path.with_suffix('.json')
    if path.is_symlink() or meta.is_symlink() or meta.with_suffix('.tmp').is_symlink():
        raise DownloadError('invalid_cache', '下载缓存不可用。')
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    try:
        state = json.loads(meta.read_text(encoding='utf-8')) if meta.exists() and meta.stat().st_size < 4096 else {}
    except (OSError, ValueError):
        state = {}
    size = path.stat().st_size if path.exists() else 0
    if size > MAX_BYTES or expected_size and size > expected_size:
        raise DownloadError('size_limit', '下载缓存大小超过附件上限。')
    if state.get('complete') and size == state.get('total') and (not expected_size or size == expected_size):
        with path.open('rb') as stream:
            digest = hashlib.file_digest(stream, 'sha256').hexdigest()
        if digest == state.get('sha256'):
            if progress:
                await progress(size, size)
            return path
    deadline = time.monotonic() + timeout
    last_report = 0.0
    attempts = 0
    while attempts < MAX_ATTEMPTS:
        attempts += 1
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        offset = path.stat().st_size if path.exists() else 0
        validator = state.get('validator', '')
        resumable = (offset > 0 and (validator or source_key and state.get('source_key') == source_key)
                     and state.get('total', 0) > offset
                     and (not expected_size or expected_size == state['total']))
        range_start = offset if validator else max(0, offset - 65536)
        headers = {'Accept-Encoding': 'identity', 'Accept': 'application/octet-stream,*/*;q=0.8'}
        if resumable:
            headers['Range'] = f'bytes={range_start}-'
            if validator:
                headers['If-Range'] = validator
        else:
            offset = 0
        try:
            async with asyncio.timeout(remaining):
                connector = aiohttp.TCPConnector(resolver=PublicResolver(), use_dns_cache=False)
                async with aiohttp.ClientSession(
                    connector=connector, trust_env=False, auto_decompress=False,
                    cookie_jar=aiohttp.DummyCookieJar(), headers=headers,
                    timeout=aiohttp.ClientTimeout(total=remaining, connect=min(10, remaining),
                                                  sock_read=min(IDLE_SECONDS, remaining)),
                ) as client:
                    current = url
                    visited = set()
                    for redirect in range(4):
                        validate_public_url(current)
                        if current in visited:
                            raise DownloadError('redirect_error', '附件下载地址发生循环跳转。')
                        visited.add(current)
                        async with client.get(current, allow_redirects=False) as response:
                            if response.status in {301, 302, 303, 307, 308}:
                                location = response.headers.get('Location')
                                if redirect == 3 or not location:
                                    raise DownloadError('redirect_error', '附件下载跳转次数过多或地址无效。')
                                current = urljoin(current, location)
                                continue
                            if response.status in {429, 500, 502, 503, 504}:
                                raise aiohttp.ClientConnectionError('Temporary download failure')
                            if response.status not in {200, 206}:
                                raise DownloadError('source_unavailable', 'QQ 文件下载地址暂不可用，请重新引用原文件后继续。')
                            if response.headers.get('Content-Encoding', 'identity').lower() != 'identity':
                                raise DownloadError('invalid_response', '附件服务器返回了不支持的传输压缩。')
                            key, value = _validator(response.headers)
                            declared = response.headers.get('Content-Length')
                            if declared is not None and not re.fullmatch(r'\d{1,10}', declared):
                                raise DownloadError('invalid_response', '附件大小信息无效。')
                            if response.status == 206:
                                match = re.fullmatch(r'bytes (\d+)-(\d+)/(\d+)', response.headers.get('Content-Range', ''))
                                if not resumable or not match:
                                    raise DownloadError('invalid_range', '附件续传响应不匹配，未拼接文件。')
                                start, end, total = map(int, match.groups())
                                if (start != range_start or end != total - 1 or total != state.get('total')
                                        or validator and response.headers.get(state.get('validator_key', 'ETag'), '') != validator
                                        or declared is not None and int(declared) != end - start + 1):
                                    raise DownloadError('invalid_range', '附件续传内容已变化，未拼接文件。')
                            else:
                                # If-Range mismatch or an origin without ranges: overwrite, never append.
                                offset = 0
                                total = int(declared) if declared is not None else expected_size
                            if total > MAX_BYTES or expected_size and total and total != expected_size:
                                raise DownloadError('size_mismatch', '附件大小与 QQ 提供的信息不一致或超过 40 MiB。')
                            overlap = b''
                            if response.status == 206 and range_start < offset:
                                with path.open('rb') as previous:
                                    previous.seek(range_start)
                                    overlap = previous.read(offset - range_start)
                            state = {'total': total, 'validator_key': key, 'validator': value,
                                     'source_key': source_key, 'complete': False}
                            with path.open('ab' if offset else 'wb') as stream:
                                os.chmod(path, 0o600)
                                # Truncate a replacement before recording its validator;
                                # a crash must never label old bytes as the new object.
                                _save(meta, state)
                                if progress:
                                    await progress(offset, total)
                                async for chunk in response.content.iter_chunked(65536):
                                    if overlap:
                                        count = min(len(chunk), len(overlap))
                                        if chunk[:count] != overlap[:count]:
                                            raise DownloadError('changed_source', 'QQ 文件续传校验不一致，未拼接文件。')
                                        overlap = overlap[count:]
                                        chunk = chunk[count:]
                                    if offset + len(chunk) > min(MAX_BYTES, total or MAX_BYTES):
                                        raise DownloadError('size_limit', '附件下载内容超过允许大小。')
                                    stream.write(chunk)
                                    offset += len(chunk)
                                    if progress and time.monotonic() - last_report >= 2:
                                        stream.flush()
                                        await progress(offset, total)
                                        last_report = time.monotonic()
                            if overlap or total and offset != total:
                                raise aiohttp.ClientPayloadError('Incomplete attachment')
                            if expected_size and offset != expected_size:
                                raise DownloadError('size_mismatch', '附件下载不完整，已保留可续传的数据。')
                            with path.open('rb') as stream:
                                digest = hashlib.file_digest(stream, 'sha256').hexdigest()
                            state.update(total=offset, complete=True, sha256=digest)
                            _save(meta, state)
                            if progress:
                                await progress(offset, offset)
                            return path
        except (asyncio.TimeoutError, aiohttp.ClientConnectionError, aiohttp.ClientPayloadError):
            if attempts < MAX_ATTEMPTS and deadline - time.monotonic() > 1:
                await asyncio.sleep(0.25 * attempts)
        except WebError as exc:
            raise DownloadError(getattr(exc, 'code', 'network_error'), str(exc)) from None
    raise DownloadError('download_timeout', '文件下载暂未完成，已保留下载进度；可要求继续，无需重新上传。')
